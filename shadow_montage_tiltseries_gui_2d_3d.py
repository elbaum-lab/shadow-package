def process_one(mat: np.ndarray, s: Settings, Ns: float, bf_diameter: float,
                case: int, defocus_sign: float, output_shape: tuple[int, int],
                apply_ctf_correction: bool = APPLY_CTF_CORRECTION,
                margin: float = MARGIN,
                canvas_override: tuple[int, int] | None = None) -> np.ndarray:
    camera = s.camera_size
    alpha_rad = s.convergence_angle_mrad / 1000.0
    if canvas_override is None:
        # Preserve the original Run 2D canvas calculation.
        canvas_x = matlab_round_positive(2 * camera + abs(Ns) * s.Nx)
        canvas_y = matlab_round_positive(2 * camera + abs(Ns) * s.Ny)
    else:
        # Used only by the preliminary Ns search.
        canvas_x = int(canvas_override[0])
        canvas_y = int(canvas_override[1])
        if canvas_x <= 0 or canvas_y <= 0:
            raise ValueError(f"Invalid canvas override: {canvas_override}")
    margin_x = int(math.floor(margin * canvas_x))
    margin_y = int(math.floor(margin * canvas_y))

    probe = np.zeros((camera, camera), dtype=np.float64)
    for ind in range(0, mat.shape[2], 10):
        im = np.nan_to_num(mat[:, :, ind], nan=0.0, posinf=0.0, neginf=0.0)
        im = np.where(im > 60000, 0, im)
        probe += im
    mask = probe > 0.5 * (float(probe.max()) + float(probe.min()))
    weighted = probe * mask
    if weighted.sum() <= 0:
        raise ValueError("Could not determine the bright-field disk.")
    m_weight = weighted / weighted.sum()
    gv = np.arange(1, camera + 1) - (1 + camera) / 2.0
    NqY, NqX = np.meshgrid(gv, gv, indexing="xy")
    Xd0 = float((NqX[mask] * m_weight[mask]).sum())
    Yd0 = float((NqY[mask] * m_weight[mask]).sum())
    mask_keep = np.sqrt((NqX - Xd0) ** 2 + (NqY - Yd0) ** 2) <= (0.5 * bf_diameter - 2)
    #print(f"Xd0={Xd0:g}, Yd0={Yd0:g}")
    xshift_dx = -Ns if case > 2 else Ns
    yshift_dy = Ns if case in (1, 3) else -Ns
    x0 = int(math.floor((1 + canvas_x) / 2.0)) - 1  # MATLAB index -> Python index
    y0 = int(math.floor((1 + canvas_y) / 2.0)) - 1
    grand_tile = np.zeros((canvas_x, canvas_y), dtype=np.float64)
    grand_count = np.zeros((canvas_x, canvas_y), dtype=np.uint32)

    frames = min(mat.shape[2], s.Nx * s.Ny)
    half_lo = camera // 2 - 1
    half_hi = camera // 2
    for ind0 in range(frames):
        # Exact source MATLAB convention: X changes fastest, Y increases by scan row.
        Xp = 1 + (ind0 % s.Nx)
        Yp = 1 + (ind0 // s.Nx)
        im = np.nan_to_num(mat[:, :, ind0], nan=0.0, posinf=0.0, neginf=0.0)
        im = np.where(im > 60000, 0, im) * mask_keep
        HR_Xc = matlab_round_positive(x0 + 1 + (Xp - s.Nx / 2.0) * xshift_dx) - 1
        HR_Yc = matlab_round_positive(y0 + 1 + (Yp - s.Ny / 2.0) * yshift_dy) - 1
        xs, xe = HR_Xc - half_lo, HR_Xc + half_hi + 1
        ys, ye = HR_Yc - half_lo, HR_Yc + half_hi + 1
        if xs < 0 or ys < 0 or xe > canvas_x or ye > canvas_y:
            continue
        grand_tile[xs:xe, ys:ye] += im
        grand_count[xs:xe, ys:ye] += mask_keep.astype(np.uint32)

    result = grand_tile / np.maximum(grand_count, 1)
    tile_image = result[::-1, :]

    if apply_ctf_correction:
        imageN = tile_image.shape[0]
        gv = np.arange(1, imageN + 1) - (1 + imageN) / 2.0
        qYr, qXr = np.meshgrid(gv, gv, indexing="xy")
        d_nm = s.step_size_nm
        qY_CTF = qYr / (imageN * d_nm / Ns)
        qX_CTF = qXr / (imageN * d_nm / Ns)
        q2 = qX_CTF ** 2 + qY_CTF ** 2
        q2_bf = (bf_diameter / imageN) ** 2
        calc_defocus_nm = bf_diameter * s.step_size_nm / (Ns * 2 * alpha_rad)
        wavelength_nm = 1.2398 / math.sqrt(s.energy_keV * (2 * 511 + s.energy_keV))
        ctf = np.sin(-defocus_sign * math.pi * calc_defocus_nm * wavelength_nm * q2)
        inv = np.where(ctf >= 0, 1.0, -1.0)
        if defocus_sign > 0:
            modulation = -np.cos((math.pi / 2.0) * (q2 / q2_bf))
            modulation[q2 > 2 * q2_bf] = 1.0
            inv *= modulation
        tile_image = np.real(np.fft.ifft2(np.fft.ifftshift(np.fft.fftshift(np.fft.fft2(tile_image)) * inv)))

    cropped = tile_image[margin_x:canvas_x - margin_x, margin_y:canvas_y - margin_y]
    #return bilinear_resize(cropped, output_shape).astype(np.float32)
    return matlab_imresize_bilinear(cropped, output_shape).astype(np.float32)


