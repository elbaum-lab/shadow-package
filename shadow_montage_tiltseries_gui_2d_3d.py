def selected(node: dict, context: str) -> str:
    try:
        return str(node["selected"])
    except (KeyError, TypeError) as exc:
        raise ValueError(f"Missing {context}.selected") from exc


def load_json(path: Path) -> dict:
    try:
        with path.open("r", encoding="utf-8-sig") as f:
            return json.load(f)
    except json.JSONDecodeError as exc:
        raise ValueError(
            f"Invalid JSON in {path} at line {exc.lineno}, column {exc.colno}: {exc.msg}"
        ) from exc


def get_raster_parameters(scan: dict, label: str) -> tuple[int, int, float]:
    mode = selected(scan["scan_mode"], f"{label}.scan_mode")
    mode_data = scan["scan_mode"].get("data", {}).get(mode)
    if not isinstance(mode_data, dict):
        raise ValueError(f"No scan parameters for {label} scan mode {mode!r}")
    try:
        return int(mode_data["Nx"]), int(mode_data["Ny"]), float(mode_data["step_size_nm"])
    except KeyError as exc:
        raise ValueError(f"Missing {label}.scan_mode.data.{mode}.{exc.args[0]}") from exc


def find_arina(scan: dict, label: str) -> tuple[bool, dict]:
    detectors = scan.get("detectors", {})
    for detector_name, detector in detectors.items():
        if isinstance(detector, dict) and detector.get("selected") == "ARINA":
            arina = detector.get("data", {}).get("ARINA", {})
            if not isinstance(arina, dict):
                raise ValueError(f"Malformed ARINA settings in {label}.{detector_name}")
            return True, arina
    return False, {}


def parse_settings(json_path: Path) -> Settings:
    root = load_json(json_path)
    microscope_mode = root.get("microscope_mode", {})
    if selected(microscope_mode, "microscope_mode") != "4D-STEM":
        raise ValueError("The metadata must have microscope_mode.selected == '4D-STEM'.")

    stem = microscope_mode.get("data", {}).get("4D-STEM")
    if not isinstance(stem, dict):
        raise ValueError("Missing microscope_mode.data['4D-STEM'] settings.")

    main = stem.get("main_scan")
    if not isinstance(main, dict):
        raise ValueError("Missing 4D-STEM main_scan.")
    try:
        main_defocus = float(main["beam"]["defocus_um"])
    except KeyError as exc:
        raise ValueError("Missing main_scan.beam.defocus_um") from exc

    if main_defocus != 0.0:
        scan = main
        source = "main_scan"
        first_scan_index = 0
    else:
        additional = stem.get("additional_scan")
        if not isinstance(additional, dict) or not additional:
            raise ValueError("main_scan defocus is 0, but additional_scan is missing or empty.")
        # JSON object keys are strings. Select the numerically first additional scan.
        numeric_keys = sorted((int(k), k) for k in additional if str(k).isdigit())
        if not numeric_keys:
            raise ValueError("additional_scan contains no numeric scan key.")
        additional_number, additional_key = numeric_keys[0]
        scan = additional[additional_key]
        source = f"additional_scan[{additional_key}]"
        first_scan_index = additional_number

    Nx, Ny, step_size_nm = get_raster_parameters(scan, source)
    beam = scan.get("beam", {})
    try:
        defocus_um = float(beam["defocus_um"])
        convergence_angle_mrad = float(beam["convergence_angle_mrad"])
        energy_keV = float(beam["energy_kv"])
    except KeyError as exc:
        raise ValueError(f"Missing {source}.beam.{exc.args[0]}") from exc
    if defocus_um == 0.0:
        raise ValueError(f"Selected {source} also has zero defocus; Ns cannot be estimated unless --Ns is given.")

    is_arina, arina = find_arina(scan, source)
    if not is_arina:
        raise ValueError(f"No detector selected as ARINA in {source}.")
    camera_selection = selected(arina.get("ARINA_camera_size", {}), "ARINA_camera_size")
    camera_size = 96 if camera_selection == "96x96" else 192
    arina_type = selected(arina.get("ARINA_type", {}), "ARINA_type")
    if arina_type not in {"commercial", "prototype"}:
        raise ValueError("ARINA_type.selected must be 'commercial' or 'prototype'.")
    position = selected(arina.get("ARINA_position", {}), "ARINA_position")

    angles = root.get("tilt_angles_deg")
    if not isinstance(angles, list) or not angles:
        raise ValueError("tilt_angles_deg must be a non-empty list.")
    repetition = int(root.get("angle_repetition_factor", 1))
    if repetition < 1:
        raise ValueError("angle_repetition_factor must be >= 1.")
    # Main data use s0,sR,s2R,...; first additional data use s1,s(1+R),...
    scan_indices = list(range(first_scan_index, len(angles), repetition))
    selected_angles = [float(angles[i]) for i in scan_indices]

    folder = json_path.resolve().parent
    master_name = str(root["master_name"])
    if not master_name:
        raise ValueError("master_name is empty.")

    return Settings(
        json_path=json_path, folder=folder, master_name=master_name,
        scan_source=source, scan_indices=scan_indices,
        tilt_angles_deg=selected_angles, Nx=Nx, Ny=Ny,
        defocus_um=defocus_um, convergence_angle_mrad=convergence_angle_mrad,
        step_size_nm=step_size_nm, energy_keV=energy_keV,
        camera_size=camera_size, dectris_arina=True,
        old_arina=(arina_type == "prototype"),
        left_to_column=(position == "left_to_column"),
    )


def _process_dataset_legacy(dset, start_index: int, array: np.ndarray) -> int:
    image_index = start_index
    for i in range(dset.shape[0]):
        array[image_index] = dset[i].astype(array.dtype, copy=False)
        image_index += 1
    return image_index


def load_legacy_h5_to_mat(h5_path: Path, nx_hint=None, ny_hint=None):
    """Loader copied from pidpc_pipeline.py; returns (H,W,T) in its MATLAB scan order."""
    with h5py.File(h5_path, "r") as f:
        entry = f["entry"]
        if isinstance(entry.get("data"), h5py.Dataset):
            dset = entry["data"]
            nimages, H, W = dset.shape
            array = np.empty((nimages, H, W), dtype=dset.dtype)
            _process_dataset_legacy(dset, 0, array)
        else:
            grp = entry["data"]
            datasets = [grp[name] for name in grp if isinstance(grp[name], h5py.Dataset)]
            if not datasets:
                raise ValueError(f"No datasets found under /entry/data in {h5_path}")
            nimages = sum(d.shape[0] for d in datasets)
            H, W, dtype = datasets[0].shape[1], datasets[0].shape[2], datasets[0].dtype
            array = np.empty((nimages, H, W), dtype=dtype)
            image_index = 0
            for dset in datasets:
                image_index = _process_dataset_legacy(dset, image_index, array)
        if array.dtype == np.uint32:
            print("Dataset is uint32; converting to uint16")
            array = array.astype(np.uint16, copy=False)
        if nx_hint and ny_hint and nx_hint * ny_hint == array.shape[0]:
            Nx, Ny = int(nx_hint), int(ny_hint)
        else:
            Nx = int(math.sqrt(array.shape[0]))
            Ny = int(array.shape[0] / Nx)
        mat = np.transpose(array.astype(np.float32, copy=False), (1, 2, 0))  # (T, H, W) -> (H, W, T)
        if mat.shape[2] != Nx * Ny:
            raise ValueError(f"Frame count {mat.shape[2]} != Nx*Ny {Nx*Ny}")
    return mat, Nx, Ny


def load_matlab_oriented(h5_path: Path, Nx: int, Ny: int) -> np.ndarray:
    mat, loaded_Nx, loaded_Ny = load_legacy_h5_to_mat(h5_path, nx_hint=Nx, ny_hint=Ny)
    if (loaded_Nx, loaded_Ny) != (Nx, Ny):
        raise ValueError(f"Loaded scan size {(loaded_Nx, loaded_Ny)} != JSON {(Nx, Ny)}")
    # Required one-time detector-plane swap. Keep the MATLAB array X/Y convention.
    mat= np.transpose(mat, (1, 0, 2))
    #print("Frames loaded:", mat.shape[2])
    return mat



def _triangle_kernel(x: np.ndarray) -> np.ndarray:
    """MATLAB bilinear interpolation kernel."""
    return np.maximum(0.0, 1.0 - np.abs(x))


def _calculate_resize_weights(
    input_length: int,
    output_length: int,
) -> tuple[np.ndarray, np.ndarray]:
    """
    Calculate MATLAB-style bilinear interpolation contributions.

    During reduction, the triangular kernel is widened by 1/scale
    to provide antialiasing.
    """

    scale = output_length / input_length

    # MATLAB-style pixel-center mapping:
    #
    # input_coordinate =
    #     output_coordinate / scale
    #     + 0.5 * (1 - 1 / scale)
    #
    # Here output coordinates are zero based.
    output_coordinates = np.arange(
        output_length,
        dtype=np.float64,
    )

    input_coordinates = (
        output_coordinates / scale
        + 0.5 * (1.0 - 1.0 / scale)
    )

    if scale < 1.0:
        # Original bilinear support is 2 pixels.
        # Antialiasing broadens it to 2/scale.
        kernel_width = 2.0 / scale

        def kernel(distance):
            return scale * _triangle_kernel(scale * distance)

    else:
        kernel_width = 2.0

        def kernel(distance):
            return _triangle_kernel(distance)

    left = np.floor(
        input_coordinates - kernel_width / 2.0
    ).astype(np.int64)

    number_of_taps = int(np.ceil(kernel_width)) + 2

    indices = (
        left[:, None]
        + np.arange(number_of_taps, dtype=np.int64)[None, :]
    )

    distances = (
        input_coordinates[:, None]
        - indices.astype(np.float64)
    )

    weights = kernel(distances)

    weight_sums = weights.sum(axis=1, keepdims=True)

    weights = np.divide(
        weights,
        weight_sums,
        out=np.zeros_like(weights),
        where=weight_sums != 0,
    )

    # MATLAB-like symmetric boundary handling.
    if input_length == 1:
        indices[:] = 0
    else:
        period = 2 * input_length

        indices = np.mod(indices, period)

        indices = np.where(
            indices < input_length,
            indices,
            period - indices - 1,
        )

    # Remove columns that contribute nothing anywhere.
    keep = np.any(np.abs(weights) > 1e-15, axis=0)

    return weights[:, keep], indices[:, keep]


def matlab_imresize_bilinear(
    image: np.ndarray,
    output_shape: tuple[int, int],
) -> np.ndarray:
    """
    MATLAB-like equivalent of:

        imresize(image, [new_size_1 new_size_2], "bilinear")

    The first and second array dimensions are preserved according
    to the MATLAB array convention used by the shadow montage.

    Downsampling uses a widened triangular antialiasing kernel.
    """

    image = np.asarray(image, dtype=np.float64)

    if image.ndim != 2:
        raise ValueError(
            f"Expected a two-dimensional image, got {image.shape}"
        )

    output_size_0 = int(output_shape[0])
    output_size_1 = int(output_shape[1])

    if output_size_0 <= 0 or output_size_1 <= 0:
        raise ValueError(
            f"Invalid output shape: {output_shape}"
        )

    if image.shape == (output_size_0, output_size_1):
        return image.copy()

    weights_0, indices_0 = _calculate_resize_weights(
        input_length=image.shape[0],
        output_length=output_size_0,
    )

    weights_1, indices_1 = _calculate_resize_weights(
        input_length=image.shape[1],
        output_length=output_size_1,
    )

    # Resize along the first MATLAB array dimension.
    temporary = np.empty(
        (output_size_0, image.shape[1]),
        dtype=np.float64,
    )

    for output_index in range(output_size_0):
        temporary[output_index, :] = np.sum(
            image[indices_0[output_index], :]
            * weights_0[output_index, :, None],
            axis=0,
        )

    # Resize along the second MATLAB array dimension.
    resized = np.empty(
        (output_size_0, output_size_1),
        dtype=np.float64,
    )

    for output_index in range(output_size_1):
        resized[:, output_index] = np.sum(
            temporary[:, indices_1[output_index]]
            * weights_1[output_index, :][None, :],
            axis=1,
        )

    if resized.shape != (output_size_0, output_size_1):
        raise RuntimeError(
            f"Resize produced {resized.shape}, "
            f"expected {(output_size_0, output_size_1)}"
        )

    return resized

def direction_parameters(s: Settings) -> tuple[int, float]:
    underfocus = s.defocus_um < 0.0
    if not s.old_arina:  # commercial ARINA
        if s.left_to_column:
            case = 4 if underfocus else 1
            defocus_sign = -1.0 if case == 4 else 1.0
        else:
            case = 1 if underfocus else 4
            defocus_sign = 1.0 if case == 4 else -1.0
    else:  # prototype ARINA
        if s.left_to_column:
            case = 2 if underfocus else 3
            defocus_sign = 1.0 if case == 3 else -1.0
        else:
            case = 3 if underfocus else 2
            defocus_sign = 1.0 if case == 2 else -1.0
    return case, defocus_sign


def probe_properties(mat: np.ndarray, camera_size: int) -> tuple[float, np.ndarray]:
    probe = np.zeros((camera_size, camera_size), dtype=np.float64)
    for ind in range(0, mat.shape[2], 10):
        im = np.nan_to_num(mat[:, :, ind], nan=0.0, posinf=0.0, neginf=0.0)
        im = np.where(im > 60000, 0, im)
        probe += im
    midv = 0.5 * (float(probe.max()) + float(probe.min()))
    mask = probe > midv
    diameter = 2.0 * math.sqrt(float(mask.sum()) / math.pi)
    return diameter, probe


def matlab_round_positive(x: float) -> int:
    return int(math.floor(x + 0.5))


