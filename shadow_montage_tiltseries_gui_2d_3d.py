def _probe_geometry_for_chunks(mat, s, bf):
    camera=s.camera_size; probe=np.zeros((camera,camera),np.float64)
    for ind in range(0,mat.shape[2],10):
        im=np.nan_to_num(mat[:,:,ind],nan=0.0,posinf=0.0,neginf=0.0)
        probe += np.where(im>60000,0,im)
    mask=probe>0.5*(float(probe.max())+float(probe.min()))
    weighted=probe*mask
    if weighted.sum()<=0: raise ValueError("Could not determine the bright-field disk.")
    mw=weighted/weighted.sum(); gv=np.arange(1,camera+1)-(1+camera)/2.0
    NqY,NqX=np.meshgrid(gv,gv,indexing="xy")
    xd0=float((NqX[mask]*mw[mask]).sum()); yd0=float((NqY[mask]*mw[mask]).sum())
    keep=np.sqrt((NqX-xd0)**2+(NqY-yd0)**2)<=(0.5*bf-2)
    return xd0,yd0,keep


def _init_one_ns_worker(shm_name,shape,dtype_string,s,bf,case,sign,Ns,extra,xd0,yd0,keep):
    global _CMAT,_CSHM,_CSET,_CBF,_CCASE,_CSIGN,_CNS,_CEXTRA,_CXD0,_CYD0,_CMASK
    _CSHM=shared_memory.SharedMemory(name=shm_name)
    _CMAT=np.ndarray(shape,dtype=np.dtype(dtype_string),buffer=_CSHM.buf)
    _CSET,_CBF,_CCASE,_CSIGN,_CNS,_CEXTRA=s,bf,case,sign,Ns,extra
    _CXD0,_CYD0,_CMASK=xd0,yd0,keep


def _one_ns_chunk(bounds):
    first,last=bounds; s=_CSET; Ns=_CNS; camera=s.camera_size
    cx=matlab_round_positive(abs(Ns)*(s.Nx+_CEXTRA)); cy=matlab_round_positive(abs(Ns)*(s.Ny+_CEXTRA))
    dx=-Ns if _CCASE>2 else Ns; dy=Ns if _CCASE in (1,3) else -Ns
    x0=int(math.floor((1+cx)/2.0))-1; y0=int(math.floor((1+cy)/2.0))-1
    tile=np.zeros((cx,cy),np.float64); count=np.zeros((cx,cy),np.uint32)
    hlo=camera//2-1; hhi=camera//2
    keep_u32=_CMASK.astype(np.uint32)
    for ind0 in range(first,last):
        Xp=1+(ind0%s.Nx); Yp=1+(ind0//s.Nx)
        im=np.nan_to_num(_CMAT[:,:,ind0],nan=0.0,posinf=0.0,neginf=0.0)
        im=np.where(im>60000,0,im)*_CMASK
        xc=int(math.floor(_CYD0+x0+dx*(Xp-(1+s.Nx)/2.0)+0.5))
        yc=int(math.floor(_CXD0+y0+dy*(Yp-(1+s.Ny)/2.0)+0.5))
        if s.old_arina: xc+=1; yc+=1
        xs,xe=xc-hlo,xc+hhi+1; ys,ye=yc-hlo,yc+hhi+1
        if xs<0 or ys<0 or xe>cx or ye>cy: continue
        tile[xs:xe,ys:ye]+=im; count[xs:xe,ys:ye]+=keep_u32
    return tile,count


def _finish_one_ns(tile,count,s,Ns,bf,sign,margin,ctf,upscaling):
    cx,cy=tile.shape; image=(tile/np.maximum(count,1))[::-1,:]
    if ctf:
        alpha=s.convergence_angle_mrad/1000.0; n=image.shape[0]
        gv=np.arange(1,n+1)-(1+n)/2.0; qYr,qXr=np.meshgrid(gv,gv,indexing="xy")
        qY=qYr/(n*s.step_size_nm/Ns); qX=qXr/(n*s.step_size_nm/Ns); q2=qX*qX+qY*qY
        q2bf=(bf/n)**2; calc=bf*s.step_size_nm/(Ns*2*alpha)
        wave=1.2398/math.sqrt(s.energy_keV*(2*511+s.energy_keV))
        transfer=np.sin(-sign*math.pi*calc*wave*q2); inv=np.where(transfer>=0,1.0,-1.0)
        if sign>0:
            mod=-np.cos((math.pi/2)*(q2/q2bf)); mod[q2>2*q2bf]=1.0; inv*=mod
        image=np.real(np.fft.ifft2(np.fft.ifftshift(np.fft.fftshift(np.fft.fft2(image))*inv)))
    mx=int(math.floor(margin*cx)); my=int(math.floor(margin*cy)); cropped=image[mx:cx-mx,my:cy-my]
    shape=(matlab_round_positive(cropped.shape[0]*upscaling/Ns),matlab_round_positive(cropped.shape[1]*upscaling/Ns))
    return matlab_imresize_bilinear(cropped,shape).astype(np.float32)


@njit(nogil=True, cache=True)
def _accumulate_chunk_numba(mat, first, last, Nx, Ny, camera, old_arina,
                            Ns, case, extra, xd0, yd0, mask_keep,
                            canvas_x, canvas_y):
    tile=np.zeros((canvas_x,canvas_y),np.float64); count=np.zeros((canvas_x,canvas_y),np.uint32)
    dx=-Ns if case>2 else Ns; dy=Ns if case==1 or case==3 else -Ns
    x0=int(math.floor((1.0+canvas_x)/2.0))-1; y0=int(math.floor((1.0+canvas_y)/2.0))-1
    hlo=camera//2-1; hhi=camera//2
    for ind0 in range(first,last):
        Xp=1+(ind0%Nx); Yp=1+(ind0//Nx)
        xc=int(math.floor(yd0+x0+dx*(Xp-(1.0+Nx)/2.0)+0.5)); yc=int(math.floor(xd0+y0+dy*(Yp-(1.0+Ny)/2.0)+0.5))
        if old_arina: xc+=1; yc+=1
        xs,xe=xc-hlo,xc+hhi+1; ys,ye=yc-hlo,yc+hhi+1
        if xs<0 or ys<0 or xe>canvas_x or ye>canvas_y: continue
        for ix in range(camera):
            tx=xs+ix
            for iy in range(camera):
                if mask_keep[ix,iy]:
                    v=mat[ix,iy,ind0]
                    if math.isfinite(v) and v<=60000.0: tile[tx,ys+iy]+=v
                    count[tx,ys+iy]+=1
    return tile,count

def _warm_numba_chunk_kernel(mat):
    keep=np.ones((1,1),np.bool_); tiny=mat[:1,:1,:1]
    return _accumulate_chunk_numba(tiny,0,0,1,1,1,False,1.0,1,0.0,0.0,0.0,keep,1,1)

def _serial_ns_parallel_chunks(mat,s,ns_list,bf,case,sign,margin,ctf,upscaling,extra):
    frames=min(mat.shape[2],s.Nx*s.Ny); workers=min(MAX_CHUNK_WORKERS,frames,max(1,os.cpu_count() or 1))
    bounds=[((frames*i)//workers,(frames*(i+1))//workers) for i in range(workers)]
    xd0,yd0,keep=_probe_geometry_for_chunks(mat,s,bf); keep=np.ascontiguousarray(keep,np.bool_)
    wt,wc=_warm_numba_chunk_kernel(mat); del wt,wc
    results=[]
    with ThreadPoolExecutor(max_workers=workers) as ex:
        for j,Ns in enumerate([float(x) for x in ns_list],1):
            cx=matlab_round_positive(abs(Ns)*(s.Nx+extra)); cy=matlab_round_positive(abs(Ns)*(s.Ny+extra))
            print(f"  Ns {j}/{len(ns_list)} = {Ns:.6g}: {workers} Numba frame chunks",flush=True)
            futures=[ex.submit(_accumulate_chunk_numba,mat,a,b,s.Nx,s.Ny,s.camera_size,s.old_arina,Ns,case,extra,xd0,yd0,keep,cx,cy) for a,b in bounds]
            partial=[f.result() for f in futures]; tile,count=partial[0]
            for pt,pc in partial[1:]: tile+=pt; count+=pc
            image=_finish_one_ns(tile,count,s,Ns,bf,sign,margin,ctf,upscaling); results.append((Ns,image))
            del partial,tile,count; gc.collect()
    return results


# Preliminary Ns search uses one complete Ns montage per thread.
# The accumulation kernel is Numba-compiled with nogil=True, so the threads
# execute the CPU-bound frame loops concurrently without multiprocessing or
# a second shared-memory copy. Run 2D and Run 3D do not use this function.
def _preliminary_ns_numba_worker(args):
    (mat, s, Ns, bf, case, sign, margin, ctf, extra,
     common_shape, xd0, yd0, mask_keep, frames) = args
    Ns = float(Ns)
    canvas_x = matlab_round_positive(abs(Ns) * (s.Nx + extra))
    canvas_y = matlab_round_positive(abs(Ns) * (s.Ny + extra))

    tile, count = _accumulate_chunk_numba(
        mat, 0, frames, s.Nx, s.Ny, s.camera_size, s.old_arina,
        Ns, case, extra, xd0, yd0, mask_keep, canvas_x, canvas_y,
    )
    image = _finish_one_ns(
        tile, count, s, Ns, bf, sign, margin, ctf, 1.0
    )

    # Keep every preliminary slice exactly the same size, using the custom
    # MATLAB-like bilinear resize with antialiasing. Usually this is already
    # the target size; the check avoids an unnecessary second resize.
    if image.shape != common_shape:
        image = matlab_imresize_bilinear(image, common_shape).astype(
            np.float32, copy=False
        )
    return int(Ns), image


def run_preliminary_ns_search(s, scan_index, margin):
    path = s.folder / f"{s.master_name}_s{scan_index}_master.h5"
    if not path.is_file():
        raise FileNotFoundError(f"Selected tilt-view file was not found:\n{path}")
    if not (0 <= margin < 0.5):
        raise ValueError("Margin must satisfy 0 <= margin < 0.5.")

    t0 = perf_counter()
    mat = load_matlab_oriented(path, s.Nx, s.Ny)
    print(
        f"Preliminary HDF5 loaded in {perf_counter() - t0:.1f} s; "
        f"shape={mat.shape}, source size={mat.nbytes / 2**30:.2f} GiB; "
        f"C-contiguous={mat.flags.c_contiguous}",
        flush=True,
    )
    if mat.shape[:2] != (s.camera_size, s.camera_size):
        raise ValueError(
            f"Detector data shape {mat.shape[:2]} does not match camera size "
            f"{s.camera_size}."
        )

    # The Numba kernel performs best on the original detector-first layout.
    # Make one contiguous float32 array only when the HDF5 transpose is not
    # already contiguous; all worker threads read this same array.
    if mat.dtype != np.float32 or not mat.flags.c_contiguous:
        t0 = perf_counter()
        mat = np.ascontiguousarray(mat, dtype=np.float32)
        print(
            f"Preliminary contiguous float32 copy completed in "
            f"{perf_counter() - t0:.1f} s",
            flush=True,
        )

    bf, _ = probe_properties(mat, s.camera_size)
    case, sign = direction_parameters(s)
    ns_max = int(math.floor(s.camera_size / 7))
    if ns_max < 1:
        raise ValueError(f"Invalid preliminary Ns maximum: {ns_max}")
    ns_list = list(range(1, ns_max + 1))
    worker_count = min(len(ns_list), 13, max(1, os.cpu_count() or 1))
    frames = min(mat.shape[2], s.Nx * s.Ny)
    extra = 2.0 * s.camera_size / ns_max
    common_shape = (
        matlab_round_positive((s.Nx + extra) * (1.0 - 2.0 * margin)),
        matlab_round_positive((s.Ny + extra) * (1.0 - 2.0 * margin)),
    )
    if common_shape[0] <= 0 or common_shape[1] <= 0:
        raise ValueError(f"Invalid preliminary output shape: {common_shape}")

    xd0, yd0, mask_keep = _probe_geometry_for_chunks(mat, s, bf)
    mask_keep = np.ascontiguousarray(mask_keep, dtype=np.bool_)

    # Compile the kernel before starting the thread pool. This prevents several
    # threads from attempting first-use compilation at the same time.
    warm_tile, warm_count = _warm_numba_chunk_kernel(mat)
    del warm_tile, warm_count

    tasks = [
        (mat, s, Ns, bf, case, sign, margin, False, extra,
         common_shape, xd0, yd0, mask_keep, frames)
        for Ns in ns_list
    ]
    print(
        f"Preliminary Numba search: {len(ns_list)} Ns values; "
        f"{worker_count} worker threads; one complete Ns per task; "
        f"output shape={common_shape}",
        flush=True,
    )
    t0 = perf_counter()
    with ThreadPoolExecutor(max_workers=worker_count) as executor:
        images = list(executor.map(_preliminary_ns_numba_worker, tasks))
    print(
        f"Preliminary Numba montage calculations completed in "
        f"{perf_counter() - t0:.1f} s",
        flush=True,
    )

    images.sort(key=lambda item: item[0])
    for Ns, image in images:
        if image.shape != common_shape:
            raise RuntimeError(
                f"Ns={Ns}: preliminary resize returned {image.shape}; "
                f"expected {common_shape}."
            )

    volume = np.stack([image for _, image in images], axis=0)[:, ::-1, :]
    out = s.folder / f"{s.master_name}_s{scan_index}_Ns1to{ns_max}.mrc"
    with mrcfile.new(out, overwrite=True) as m:
        m.set_data(np.transpose(volume, (0, 2, 1)).astype(np.float32, copy=False))
        m.update_header_stats()
    print(f"Wrote preliminary Ns stack: {out}", flush=True)
    return out


def _round_signed(x): return int(math.copysign(math.floor(abs(float(x))+0.5),x))


def _ns_list_3d(s,ns_best,bf,size_z,upscaling):
    alpha=s.convergence_angle_mrad/1000.0; step=s.step_size_nm*0.001
    wave=1.2398/math.sqrt(s.energy_keV*(2*511+s.energy_keV))
    depth=(step/upscaling)*size_z; dof=(wave/1000.0)/alpha**2; df=max(dof,depth/10.0)
    center=bf*step/(ns_best*2*alpha)
    left=math.floor(min(center-0.1,0.5*depth)/df); right=math.floor(0.5*depth/df)
    dfs=center+df*np.arange(-left,right+1,dtype=float)
    ns=np.clip(bf*step/(2*alpha*dfs),2.0,bf/3.0)
    i1=np.where(ns==ns[0])[0].max(); i2=np.where(ns==ns[-1])[0].min()
    return center,depth,dfs[i1:i2+1],ns[i1:i2+1]


def run_3d(json_path,Ns_override,size_z,settings_override=None,rendered_upscaling=REQUIRED_UPSCALING,
           apply_ctf_correction=APPLY_CTF_CORRECTION,margin=MARGIN):
    s=settings_override if settings_override is not None else parse_settings(json_path)
    if size_z<=0: raise ValueError("Number of depth slices must be positive.")
    paths=[s.folder/f"{s.master_name}_s{i}_master.h5" for i in s.scan_indices]
    first=next((p for p in paths if p.is_file()),None)
    if first is None: raise FileNotFoundError("No selected tilt-view HDF5 file was found.")
    first_mat=load_matlab_oriented(first,s.Nx,s.Ny); bf,_=probe_properties(first_mat,s.camera_size)
    alpha=s.convergence_angle_mrad/1000.0
    ns_best=Ns_override if Ns_override is not None else bf*(s.step_size_nm*0.001)/(2*abs(s.defocus_um)*alpha)
    case,sign=direction_parameters(s); extra=2.0*s.camera_size/ns_best
    cx=matlab_round_positive(ns_best*(s.Nx+extra)); cy=matlab_round_positive(ns_best*(s.Ny+extra))
    nx=matlab_round_positive((cx-2*math.floor(margin*cx))*rendered_upscaling/ns_best)
    ny=matlab_round_positive((cy-2*math.floor(margin*cy))*rendered_upscaling/ns_best)
    center,span,dfs,ns_list=_ns_list_3d(s,ns_best,bf,size_z,rendered_upscaling)
    print("3D defocus points (um):",dfs); print("3D Ns list:",ns_list)
    outputs=[]
    tiltview_best_by_acquisition=[]  # (angle_deg, scan_index, Ns_best montage)
    for k,(scan,ang,path) in enumerate(zip(s.scan_indices,s.tilt_angles_deg,paths),1):
        if not path.is_file(): print(f"[{k}/{len(paths)}] Missing {path.name}; skipped."); continue
        print(f"[{k}/{len(paths)}] Loading complete HDF5 for s{scan}: {path.name}",flush=True)
        mat=first_mat if path==first else load_matlab_oriented(path,s.Nx,s.Ny)
        images=_serial_ns_parallel_chunks(mat,s,ns_list,bf,case,sign,margin,apply_ctf_correction,rendered_upscaling,extra)
        tiles=[im for _,im in images]; ib=np.where(np.abs(ns_list-ns_best)<0.01)[0]
        best=tiles[int(ib[0])] if len(ib) else _serial_ns_parallel_chunks(mat,s,[ns_best],bf,case,sign,margin,apply_ctf_correction,rendered_upscaling,extra)[0][1]
        # Save the final cropped/resized Ns_best shadow montage for the 2D tilt series.
        # Copy because the larger per-tilt arrays are released later.
        best_for_tilt = best if best.shape == (nx,ny) else matlab_imresize_bilinear(best,(nx,ny)).astype(np.float32)
        tiltview_best_by_acquisition.append((float(ang), int(scan), best_for_tilt.copy()))
        vol=np.full((nx,3*ny,size_z),float(np.mean(best)),np.float32)
        dmin,dmax=center-0.5*span,center+0.5*span; angle=math.radians(ang)
        for iz in range(size_z):
            depth=dmin+iz*(dmax-dmin)/size_z; suitable=(s.step_size_nm*0.001)*bf/(depth*2*alpha)
            ni=int(np.argmin(np.abs(ns_list-suitable))); slide=((iz+1)-(1+size_z)/2)*math.tan(angle)
            mid=(1+3*ny)/2; a=_round_signed(slide+mid-(ny/2)/math.cos(angle)); b=_round_signed(slide+mid+(ny/2)/math.cos(angle))
            vol[:,a-1:b,iz]=matlab_imresize_bilinear(tiles[ni],(nx,b-(a-1)))
        c0=_round_signed((1+3*ny)/2-ny/2)-1; vol=vol[:,c0:c0+ny,:]
        out=s.folder/f"{s.master_name}_s{scan}_3dmontage.mrc"
        pixel_size_A = s.step_size_nm * 10.0 / rendered_upscaling
        with mrcfile.new(out, overwrite=True) as m:
            m.set_data(np.transpose(vol, (2, 1, 0)).astype(np.float32))
            # MRC voxel_size order is x, y, z. The reconstructed 3D montage
            # uses the same physical sampling along all three axes.
            m.voxel_size = (pixel_size_A, pixel_size_A, pixel_size_A)
            m.update_header_stats()
        outputs.append(out)
        print(f"Wrote {out}; voxel size = {pixel_size_A:g} A in x/y/z")
        del mat,images,tiles,best,vol; gc.collect()

    # Save tilt angles in acquisition order.
    rawtlt_acquisition_out = s.folder / f"{s.master_name}.rawtlt"
    with rawtlt_acquisition_out.open("w", encoding="ascii") as f:
        for angle in s.tilt_angles_deg:
            f.write(f"{angle:g}\n")
    print(
        "Acquisition-order tilt angles:",
        s.tilt_angles_deg,
        flush=True,
    )
    print(f"Wrote {rawtlt_acquisition_out}", flush=True)

    # Sort the Ns_best montages by physical tilt angle, not acquisition index,
    # and save the reordered tilt-angle file.
    reordered = sorted(
        tiltview_best_by_acquisition,
        key=lambda item: item[0]
    )

    rawtlt_reorder_out = (
        s.folder / f"{s.master_name}_Tiltview_reorder.rawtlt"
    )

    with rawtlt_reorder_out.open("w", encoding="ascii") as f:
        for angle, _, _ in reordered:
            f.write(f"{angle:g}\n")
    print(
        "Reordered tilt angles:",
        [angle for angle, _, _ in reordered],
        flush=True,
    )
    print(f"Wrote {rawtlt_reorder_out}", flush=True)           
           
    if reordered:
        tilt_volume = np.stack(
            [image for _, _, image in reordered], axis=0
        )[:,:,:] #[:, ::-1, :]
        tilt_mrc_data = np.transpose(
            tilt_volume, (0, 2, 1)
        ).astype(np.float32, copy=False)
        tilt_output = s.folder / f"{s.master_name}_Tiltview_reorder.mrc"
        pixel_size_A = s.step_size_nm * 10.0 / rendered_upscaling
        with mrcfile.new(tilt_output, overwrite=True) as m:
            m.set_data(tilt_mrc_data)
            # X/Y are physical image axes. Z enumerates tilt views, so it is
            # not a physical spatial sampling interval; retain a neutral 1 A.
            m.voxel_size = (pixel_size_A, pixel_size_A, 1.0)
            m.update_header_stats()
        print(
            "Tiltview_reorder angle order:",
            [angle for angle, _, _ in reordered],
            flush=True,
        )
        print(
            f"Wrote {tilt_output}; voxel size = {pixel_size_A:g} A in x/y",
            flush=True,
        )
    else:
        print("No completed tilt views were available for Tiltview_reorder.")

    return outputs


import shutil

def execute_in_imod(dataset_dir, master_name, number_of_cpus=8):
    dataset_dir = Path(dataset_dir).resolve()

    imod_dir_text = os.environ.get("IMOD_DIR")
    imod_python_text = os.environ.get("IMOD_PYTHON")

    if not imod_dir_text:
        raise RuntimeError(
            "The Windows environment variable IMOD_DIR is not defined."
        )

    if not imod_python_text:
        raise RuntimeError(
            "The Windows environment variable IMOD_PYTHON is not defined."
        )

    imod_dir = Path(imod_dir_text)
    imod_python = Path(imod_python_text)

    batchruntomo = imod_dir / "bin" / "batchruntomo"
    template_adoc = Path(__file__).resolve().parent / "template.adoc"

    # ----------------------------------------------------------
    # Original input/output files
    # ----------------------------------------------------------

    source_mrc = dataset_dir / f"{master_name}.mrc"
    source_rawtlt = dataset_dir / f"{master_name}.rawtlt"

    if not source_mrc.exists():
        raise FileNotFoundError(
            f"MRC file not found:\n{source_mrc}"
        )

    if not source_rawtlt.exists():
        raise FileNotFoundError(
            f"RAWTLT file not found:\n{source_rawtlt}"
        )

    # ----------------------------------------------------------
    # Create separate IMOD working directory
    # ----------------------------------------------------------

    imod_work_dir = dataset_dir / "IMOD_tmp"
    imod_work_dir.mkdir(exist_ok=True)

    work_mrc = imod_work_dir / source_mrc.name
    work_rawtlt = imod_work_dir / source_rawtlt.name

    print("Copying files to IMOD working directory...")

    shutil.copy2(source_mrc, work_mrc)
    shutil.copy2(source_rawtlt, work_rawtlt)

    print("IMOD working directory:", imod_work_dir)
    print("MRC:", work_mrc)
    print("RAWTLT:", work_rawtlt)

    # ----------------------------------------------------------
    # CMD.EXE cannot use UNC path as current directory.
    # Map the IMOD working directory to a drive letter.
    # ----------------------------------------------------------

    imod_dataset_dir = imod_work_dir
    mapped_drive = None

    if str(imod_work_dir).startswith("\\\\"):
        mapped_drive = "M:"

        subprocess.run(
            ["net", "use", mapped_drive, "/delete", "/y"],
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
        )

        result = subprocess.run(
            [
                "net",
                "use",
                mapped_drive,
                str(imod_work_dir),
            ],
            text=True,
            capture_output=True,
        )

        if result.returncode != 0:
            raise RuntimeError(
                "Could not map IMOD working directory:\n\n"
                + result.stdout
                + result.stderr
            )

        imod_dataset_dir = Path(mapped_drive + "\\")

        print(
            "Mapped IMOD working directory:\n"
            f"  {imod_work_dir}\n"
            f"  -> {imod_dataset_dir}"
        )

    # ----------------------------------------------------------
    # Run IMOD
    # ----------------------------------------------------------

    env = os.environ.copy()
    env["IMOD_DIR"] = str(imod_dir)

    command = [
        str(imod_python),
        "-u",
        str(batchruntomo),

        "-directive",
        str(template_adoc),

        "-root",
        master_name,

        "-current",
        str(imod_dataset_dir),

        "-cpus",
        str(number_of_cpus),

        "-end",
        "8",

        "-exit",
    ]

    try:
        process = subprocess.run(
            command,
            cwd=str(imod_dataset_dir),
            env=env,
            text=True,
            stdout=subprocess.PIPE,
            stderr=subprocess.STDOUT,
        )

        print(process.stdout)

        if process.returncode != 0:
            raise RuntimeError(
                "IMOD alignment failed.\n\n"
                f"Return code: {process.returncode}\n\n"
                f"{process.stdout}"
            )

        # ------------------------------------------------------
        # Copy desired results back to original data directory
        # ------------------------------------------------------

        generated_xf = imod_work_dir / f"{master_name}.xf"
        generated_ali = imod_work_dir / f"{master_name}_ali.mrc"

        if not generated_xf.exists():
            raise RuntimeError(
                "IMOD completed, but XF file was not produced:\n"
                f"{generated_xf}"
            )

        output_xf = dataset_dir / f"{master_name}.xf"

        shutil.copy2(
            generated_xf,
            output_xf,
        )

        print("XF copied to:", output_xf)

        return output_xf, generated_ali

    finally:
        # Disconnect temporary network mapping
        if mapped_drive is not None:
            subprocess.run(
                ["net", "use", mapped_drive, "/delete", "/y"],
                stdout=subprocess.DEVNULL,
                stderr=subprocess.DEVNULL,
            )




def make_output_path(s: Settings) -> Path:
    return s.folder / f"{s.master_name}_{s.scan_source.replace('[', '_').replace(']', '')}_Tiltview.mrc"





def run(json_path: Path, Ns_override: float | None,
        settings_override: Settings | None = None,
        rendered_upscaling: float = REQUIRED_UPSCALING,
        apply_ctf_correction: bool = APPLY_CTF_CORRECTION,
        margin: float = MARGIN) -> Path:
    s = settings_override if settings_override is not None else parse_settings(json_path)
    if rendered_upscaling <= 0:
        raise ValueError("Rendered upscaling must be positive.")
    if not (0 <= margin < 0.5):
        raise ValueError("Margin must satisfy 0 <= margin < 0.5.")
    paths = [s.folder / f"{s.master_name}_s{i}_master.h5" for i in s.scan_indices]
    existing_first = next((p for p in paths if p.is_file()), None)
    if existing_first is None:
        raise FileNotFoundError("No matching HDF5 file was found. First candidates:\n  " + "\n  ".join(map(str, paths[:5])))

    first_mat = load_matlab_oriented(existing_first, s.Nx, s.Ny)
    if first_mat.shape[:2] != (s.camera_size, s.camera_size):
        raise ValueError(f"Detector data shape {first_mat.shape[:2]} does not match JSON camera size {s.camera_size}.")
    bf_diameter, _ = probe_properties(first_mat, s.camera_size)
    if Ns_override is not None:
        if Ns_override <= 0:
            raise ValueError("--Ns must be positive.")
        Ns = float(Ns_override)
    else:
        alpha_rad = s.convergence_angle_mrad / 1000.0
        Ns = bf_diameter * (s.step_size_nm * 0.001) / (2 * abs(s.defocus_um) * alpha_rad)
    if Ns <= 0 or not np.isfinite(Ns):
        raise ValueError(f"Invalid Ns value: {Ns}")

    case, defocus_sign = direction_parameters(s)
    canvas_x = matlab_round_positive(2 * s.camera_size + abs(Ns) * s.Nx)
    canvas_y = matlab_round_positive(2 * s.camera_size + abs(Ns) * s.Ny)
    crop_x = canvas_x - 2 * int(math.floor(margin * canvas_x))
    crop_y = canvas_y - 2 * int(math.floor(margin * canvas_y))
    output_shape = (
        matlab_round_positive(crop_x * rendered_upscaling / Ns),
        matlab_round_positive(crop_y * rendered_upscaling / Ns),
    )

    print(f"Metadata: {json_path}")
    print(f"Parameter source: {s.scan_source}")
    print(f"MATLAB-order Nx, Ny: {s.Nx}, {s.Ny}")
    print(f"Camera: {s.camera_size}x{s.camera_size}; ARINA: {'prototype' if s.old_arina else 'commercial'}")
    print(f"ARINA left_to_column: {s.left_to_column}; direction case: {case}")
    print(f"BF disk diameter: {bf_diameter:.4f} px; Ns: {Ns:.6g}")
    print(f"Output image shape in MATLAB X/Y order: {output_shape}")

    volume = np.zeros((len(paths), output_shape[0], output_shape[1]), dtype=np.float32)
    for out_i, (scan_i, angle, path) in enumerate(zip(s.scan_indices, s.tilt_angles_deg, paths)):
        print(f"[{out_i + 1}/{len(paths)}] s{scan_i}, angle={angle:g}: {path.name}")
        if not path.is_file():
            print("  Missing; writing a black tilt image.")
            continue
        try:
            mat = first_mat if path == existing_first else load_matlab_oriented(path, s.Nx, s.Ny)
            volume[out_i] = process_one(mat, s, Ns, bf_diameter, case, defocus_sign, output_shape,
                                      apply_ctf_correction=apply_ctf_correction, margin=margin)
        except Exception as exc:
            print(f"  Failed ({exc}); writing a black tilt image.")

    # MATLAB ends with tilt_cor = tilt(end:-1:1,:,:). MRC stores (Z,Y,X).
    # The per-image arrays retain MATLAB's first/second dimensions; transpose each image for MRC Y/X.
    volume = volume[:, ::-1, :]
    mrc_data = np.transpose(volume, (0, 2, 1)).astype(np.float32, copy=False)
    output = make_output_path(s)
    output.parent.mkdir(parents=True, exist_ok=True)
    with mrcfile.new(output, overwrite=True) as mrc:
        mrc.set_data(mrc_data)
        mrc.voxel_size = (s.step_size_nm * 10 / rendered_upscaling,) * 3
        mrc.update_header_stats()
    print(f"Wrote: {output}")
    return output


def _first_existing_h5(s: Settings) -> Path:
    paths = [s.folder / f"{s.master_name}_s{i}_master.h5" for i in s.scan_indices]
    first = next((path for path in paths if path.is_file()), None)
    if first is None:
        raise FileNotFoundError(
            "No matching HDF5 file was found beside the selected JSON. First candidates:\n  "
            + "\n  ".join(str(path) for path in paths[:5])
        )
    return first


